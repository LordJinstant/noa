'use strict';

/**
 * Synchronous better-sqlite3-shaped client backed by Postgres (Supabase).
 *
 * The NOA server was written against better-sqlite3, which is synchronous.
 * Routing, auth, and scoring logic stay untouched: prepare().get/all/run/exec
 * still return values directly. Queries run on a worker thread so the blocking
 * wait does not deadlock the pg driver.
 *
 * SQL written for SQLite is translated here (? placeholders, datetime('now'),
 * AUTOINCREMENT, PRAGMA, INSERT OR IGNORE / REPLACE, date(), COLLATE NOCASE).
 *
 * Use a Supabase *session* pooler or direct connection (port 5432).
 * Do not use the transaction pooler (port 6543).
 */

const { Worker } = require('worker_threads');
const path = require('path');

const HEADER = 8;
const STATE = 0;
const LENGTH = 1;
const IDLE = 0;
const REQUEST = 1;
const OK = 2;
const ERR = 3;
const READY = 10;

const ID_TABLES = new Set([
  'users',
  'staff_follows',
  'assessments',
  'quizzes',
  'quiz_questions',
  'quiz_attempts',
  'staff_ratings',
  'msg_channels',
  'msg_messages'
]);

/** Primary keys for INSERT OR REPLACE tables that have no single id column. */
const REPLACE_KEYS = {
  quiz_retakes: ['quiz_id', 'student_id'],
  quiz_retake_allows: ['quiz_id', 'student_id'],
  staff_follows: ['student_id', 'staff_id'],
  staff_ratings: ['staff_id', 'student_id'],
  quiz_attempts: ['quiz_id', 'student_id'],
  msg_channel_reads: ['user_key', 'channel_id'],
  msg_mutes: ['user_id']
};

function redactDatabaseUrl(url) {
  try {
    const u = new URL(url);
    const dbName = (u.pathname || '').replace(/^\//, '') || 'postgres';
    return 'postgres://' + u.hostname + (u.port ? ':' + u.port : '') + '/' + dbName;
  } catch (e) {
    return 'postgres';
  }
}

function splitSql(sql) {
  const stmts = [];
  let cur = '';
  let inStr = false;
  let depth = 0;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'") {
      if (inStr && sql[i + 1] === "'") {
        cur += "''";
        i++;
        continue;
      }
      inStr = !inStr;
      cur += c;
      continue;
    }
    if (!inStr) {
      if (c === '(') depth++;
      else if (c === ')') depth = Math.max(0, depth - 1);
      else if (c === ';' && depth === 0) {
        if (cur.trim()) stmts.push(cur.trim());
        cur = '';
        continue;
      }
    }
    cur += c;
  }
  if (cur.trim()) stmts.push(cur.trim());
  return stmts;
}

function literal(value) {
  if (value === undefined || value === null) return 'NULL';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return 'NULL';
    return String(value);
  }
  if (typeof value === 'bigint') return value.toString();
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (value instanceof Date) {
    return "'" + value.toISOString().replace(/'/g, "''") + "'";
  }
  return "'" + String(value).replace(/\0/g, '').replace(/'/g, "''") + "'";
}

/** Replace ? placeholders that are outside SQL strings. Bound values may themselves contain ?. */
function bindLiterals(sql, params) {
  const values = params || [];
  let out = '';
  let inStr = false;
  let p = 0;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'") {
      if (inStr && sql[i + 1] === "'") {
        out += "''";
        i++;
        continue;
      }
      inStr = !inStr;
      out += c;
      continue;
    }
    if (!inStr && c === '?') {
      if (p >= values.length) {
        throw new Error('Not enough SQL parameters');
      }
      out += literal(values[p++]);
      continue;
    }
    out += c;
  }
  if (p !== values.length) {
    throw new Error('Too many SQL parameters (' + values.length + ' for ' + p + ' placeholders)');
  }
  return out;
}

function translateStatement(sql) {
  let s = String(sql || '').trim();
  const pragma = s.match(/^PRAGMA\s+table_info\s*\(\s*['"]?([A-Za-z_][\w]*)['"]?\s*\)\s*$/i);
  if (pragma) {
    const table = pragma[1].toLowerCase().replace(/'/g, '');
    return (
      "SELECT column_name AS name, data_type AS type " +
      "FROM information_schema.columns " +
      "WHERE table_schema = 'public' AND table_name = '" + table + "' " +
      "ORDER BY ordinal_position"
    );
  }

  s = s.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  s = s.replace(/datetime\(\s*'now'\s*\)/gi,
    "(to_char(NOW() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))");
  s = s.replace(/ORDER\s+BY\s+name\s+COLLATE\s+NOCASE/gi, 'ORDER BY lower(name)');
  s = s.replace(/\bCOLLATE\s+NOCASE\b/gi, '');
  s = s.replace(/\bdate\s*\(\s*([^()]+)\s*\)/gi, 'substring(($1)::text, 1, 10)');

  let ignore = false;
  let replace = false;
  if (/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(s)) {
    ignore = true;
    s = s.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i, 'INSERT INTO');
  } else if (/\bINSERT\s+OR\s+REPLACE\s+INTO\b/i.test(s)) {
    replace = true;
    s = s.replace(/\bINSERT\s+OR\s+REPLACE\s+INTO\b/i, 'INSERT INTO');
  }

  if (ignore && !/\bON\s+CONFLICT\b/i.test(s)) {
    s = s.replace(/\s*;?\s*$/, '') + ' ON CONFLICT DO NOTHING';
  }

  if (replace && !/\bON\s+CONFLICT\b/i.test(s)) {
    const header = s.match(/INSERT\s+INTO\s+([A-Za-z_][\w]*)\s*\(([^)]+)\)/i);
    if (!header) {
      throw new Error('Could not translate INSERT OR REPLACE: ' + s.slice(0, 180));
    }
    const table = header[1].toLowerCase();
    const cols = header[2].split(',').map(c => c.trim().replace(/"/g, '').toLowerCase());
    const keys = REPLACE_KEYS[table];
    if (!keys) {
      throw new Error('INSERT OR REPLACE has no known primary key for table ' + table);
    }
    const updates = cols
      .filter(c => keys.indexOf(c) === -1)
      .map(c => c + ' = EXCLUDED.' + c);
    s = s.replace(/\s*;?\s*$/, '');
    if (!updates.length) {
      s += ' ON CONFLICT (' + keys.join(', ') + ') DO NOTHING';
    } else {
      s += ' ON CONFLICT (' + keys.join(', ') + ') DO UPDATE SET ' + updates.join(', ');
    }
  }

  return s;
}

function maybeReturning(sql) {
  const m = String(sql).match(/^\s*INSERT\s+INTO\s+([A-Za-z_][\w]*)\b/i);
  if (!m) return sql;
  if (!ID_TABLES.has(m[1].toLowerCase())) return sql;
  if (/\bRETURNING\b/i.test(sql)) return sql;
  return sql.replace(/\s*;?\s*$/, '') + ' RETURNING id';
}

function finalizeSql(sql, params, forRun) {
  const parts = splitSql(sql);
  if (parts.length !== 1) {
    throw new Error('prepare() got ' + parts.length + ' statements; use exec() for scripts');
  }
  let text = bindLiterals(translateStatement(parts[0]), params || []);
  if (forRun) text = maybeReturning(text);
  return text;
}

class Statement {
  constructor(db, sql) {
    this.db = db;
    this.sql = sql;
  }

  get(...params) {
    const rows = this.all(...params);
    return rows.length ? rows[0] : undefined;
  }

  all(...params) {
    const text = finalizeSql(this.sql, params, false);
    const res = this.db._query(text);
    return res.rows || [];
  }

  run(...params) {
    const text = finalizeSql(this.sql, params, true);
    const res = this.db._query(text);
    const row = res.rows && res.rows[0];
    let id;
    if (row && row.id != null && row.id !== '') id = Number(row.id);
    return {
      changes: Number(res.rowCount) || 0,
      lastInsertRowid: id
    };
  }
}

class Database {
  constructor(connectionString) {
    const url = String(connectionString || '').trim();
    if (!url) {
      throw new Error(
        'DATABASE_URL is not set. Paste the Supabase Postgres URI (Session pooler or Direct, port 5432) into .env as DATABASE_URL.'
      );
    }
    if (!/^postgres(ql)?:\/\//i.test(url)) {
      throw new Error(
        'Expected a Postgres connection URL, not a SQLite file. Set DATABASE_URL. Received: ' + url.slice(0, 48)
      );
    }
    this.connectionString = url;
    this.label = redactDatabaseUrl(url);
    const mb = Number(process.env.NOA_PG_BUFFER_MB);
    this.bufferBytes = (Number.isFinite(mb) && mb >= 4 ? mb : 32) * 1024 * 1024;
    this.session = null;
    this._open();
  }

  _open() {
    const sab = new SharedArrayBuffer(this.bufferBytes);
    const int32 = new Int32Array(sab);
    const bytes = new Uint8Array(sab);
    const worker = new Worker(path.join(__dirname, 'pg-worker.js'), {
      workerData: {
        sab,
        connectionString: this.connectionString
      }
    });
    const session = { sab, int32, bytes, worker };
    worker.on('error', (err) => {
      console.error('Postgres worker error:', err && err.message ? err.message : err);
    });
    this.session = session;
    this._waitReady();
  }

  _closeSession() {
    const session = this.session;
    this.session = null;
    if (session && session.worker) {
      try { session.worker.terminate(); } catch (e) {}
    }
  }

  _waitReady() {
    const int32 = this.session.int32;
    const deadline = Date.now() + 20000;
    while (true) {
      const state = Atomics.load(int32, STATE);
      if (state === READY) break;
      if (state === ERR) {
        const res = this._readJson();
        this._closeSession();
        throw new Error('Postgres connection failed: ' + ((res && res.error) || 'unknown error') +
          ' (' + this.label + ')');
      }
      if (Date.now() > deadline) {
        this._closeSession();
        throw new Error('Postgres connection timed out (' + this.label + ')');
      }
      Atomics.wait(int32, STATE, state, 500);
    }
    Atomics.store(int32, STATE, IDLE);
    Atomics.notify(int32, STATE, 1);
  }

  _writeJson(obj) {
    const json = JSON.stringify(obj);
    const buf = Buffer.from(json, 'utf8');
    const bytes = this.session.bytes;
    if (buf.length > bytes.length - HEADER) {
      throw new Error('Query is larger than the Postgres buffer (' + this.bufferBytes + ' bytes). Raise NOA_PG_BUFFER_MB.');
    }
    bytes.set(buf, HEADER);
    Atomics.store(this.session.int32, LENGTH, buf.length);
  }

  _readJson() {
    const int32 = this.session.int32;
    const len = Atomics.load(int32, LENGTH);
    if (!len) return null;
    const json = Buffer.from(this.session.bytes.subarray(HEADER, HEADER + len)).toString('utf8');
    return JSON.parse(json);
  }

  _query(sqlText) {
    if (!this.session) this._open();
    const int32 = this.session.int32;
    this._writeJson({ sql: sqlText });
    Atomics.store(int32, STATE, REQUEST);
    Atomics.notify(int32, STATE, 1);

    const deadline = Date.now() + 60000;
    while (true) {
      const state = Atomics.load(int32, STATE);
      if (state === OK || state === ERR) break;
      if (Date.now() > deadline) {
        this._closeSession();
        throw new Error('Postgres query timed out after 60s');
      }
      Atomics.wait(int32, STATE, state, 1000);
    }

    const state = Atomics.load(int32, STATE);
    let res = null;
    try {
      res = this._readJson();
    } catch (e) {
      res = { ok: false, error: 'Bad response from Postgres worker: ' + e.message };
    }
    Atomics.store(int32, STATE, IDLE);
    Atomics.notify(int32, STATE, 1);

    if (state === ERR || !res || res.ok === false) {
      const err = new Error((res && res.error) || 'Postgres query failed');
      if (res && res.code) err.code = res.code;
      throw err;
    }
    return res;
  }

  prepare(sql) {
    return new Statement(this, sql);
  }

  exec(sql) {
    const parts = splitSql(sql);
    for (let i = 0; i < parts.length; i++) {
      const text = bindLiterals(translateStatement(parts[i]), []);
      this._query(text);
    }
    return this;
  }

  close() {
    this._closeSession();
  }
}

module.exports = Database;
module.exports.Database = Database;
module.exports.translateStatement = translateStatement;
module.exports.bindLiterals = bindLiterals;
module.exports.splitSql = splitSql;
module.exports.finalizeSql = finalizeSql;
module.exports.redactDatabaseUrl = redactDatabaseUrl;